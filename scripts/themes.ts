// Regenerates src/core/themes-bundled.ts from Omarchy's stock themes, so VibeForge can wear any
// of them on a machine without Omarchy, or without that theme:
//
//   node scripts/themes.ts [themes folder]
//
// The folder defaults to $OMARCHY_PATH/themes (/usr/share/omarchy/themes). Only colors.toml is
// read; the app derives everything else from it, as it does for an installed theme.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const source = process.argv[2] ?? path.join(process.env.OMARCHY_PATH ?? "/usr/share/omarchy", "themes");

const themes = fs
  .readdirSync(source, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && fs.existsSync(path.join(source, entry.name, "colors.toml")))
  .map((entry) => entry.name)
  .sort();

const lines = themes.map((id) => {
  const colors: Record<string, string> = {};
  for (const raw of fs.readFileSync(path.join(source, id, "colors.toml"), "utf8").split("\n")) {
    const match = raw.trim().match(/^([A-Za-z0-9_.-]+)\s*=\s*"([^"]*)"/);
    if (match) colors[match[1]] = match[2].startsWith("#") ? match[2].toLowerCase() : match[2];
  }
  return `  { id: ${JSON.stringify(id)}, colors: ${JSON.stringify(colors)} },`;
});

fs.writeFileSync(
  path.join(root, "src", "core", "themes-bundled.ts"),
  `// Generated by \`node scripts/themes.ts\`: the colors.toml of each of Omarchy's stock themes
// (MIT, https://github.com/basecamp/omarchy). Don't edit by hand.

export const BUNDLED_THEMES: ReadonlyArray<{ id: string; colors: Readonly<Record<string, string>> }> = [
${lines.join("\n")}
];
`,
);
console.log(`${themes.length} themes from ${source}`);
